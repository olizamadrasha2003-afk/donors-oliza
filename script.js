function loadDonorForEdit(id) {
    if (!id) {
        document.getElementById('adminId').value = '';
        document.getElementById('adminName').value = '';
        document.getElementById('adminFather').value = '';
        document.getElementById('adminAddress').value = '';
        document.getElementById('adminMobile').value = '';
        document.getElementById('adminGender').value = 'পুরুষ';
        document.getElementById('adminAmount').value = '';
        return;
    }

    const donor = donors.find(d => d.id == id);
    if (donor) {
        document.getElementById('adminId').value = donor.id;
        document.getElementById('adminName').value = donor.name;
        document.getElementById('adminFather').value = donor.father;
        document.getElementById('adminAddress').value = donor.address;
        document.getElementById('adminMobile').value = donor.mobile;
        document.getElementById('adminGender').value = donor.gender || 'পুরুষ';
        document.getElementById('adminAmount').value = donor.amount;
    }
}

