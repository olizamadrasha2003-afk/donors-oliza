// স্মার্ট CSV পার্সার (নতুন জেন্ডার কলাম সহ)
function parseCSV(csv) {
    const lines = csv.trim().split("\n");
    return lines.slice(1).map(line => {
        const parts = line.split(",");
        if (parts.length < 7) return null;

        const id = parseInt(parts[0]) || 0;
        const name = parts[1] ? parts[1].trim() : "";
        const father = parts[2] ? parts[2].trim() : "";
        const amount = parts[parts.length - 1] ? parts[parts.length - 1].trim() : "";
        const gender = parts[parts.length - 2] ? parts[parts.length - 2].trim() : "পুরুষ";
        const mobile = parts[parts.length - 3] ? parts[parts.length - 3].trim() : "";
        
        // আইডি, নাম, পিতা, মোবাইল, জেন্ডার ও দানের পরিমাণ বাদে মাঝের অংশ ঠিকানা
        const addressParts = parts.slice(3, parts.length - 3);
        const address = addressParts.join(", ").trim();

        return { id, name, father, address, mobile, gender, amount };
    }).filter(item => item !== null);
}

