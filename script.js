// এডিটের জন্য ডাটা ফর্মে লোড করা
function loadDonorForEdit(id) {
    if (!id) {
        document.getElementById('adminId').value = '';
        document.getElementById('adminName').value = '';
        document.getElementById('adminFather').value = '';
        document.getElementById('adminAddress').value = '';
        document.getElementById('adminMobile').value = '';
        document.getElementById('adminGender').value = 'পুরুষ';
        document.getElementById('adminAmount').value = '';
        return;
    }

    const donor = donors.find(d => d.id == id);
    if (donor) {
        document.getElementById('adminId').value = donor.id;
        document.getElementById('adminName').value = donor.name;
        document.getElementById('adminFather').value = donor.father;
        document.getElementById('adminAddress').value = donor.address;
        document.getElementById('adminMobile').value = donor.mobile;
        document.getElementById('adminGender').value = donor.gender || 'পুরুষ';
        document.getElementById('adminAmount').value = donor.amount;
    }
}

// তথ্য সেভ বা আপডেট করা
function saveDonorData() {
    const id = parseInt(document.getElementById('adminId').value);
    const name = document.getElementById('adminName').value;
    const father = document.getElementById('adminFather').value;
    const address = document.getElementById('adminAddress').value;
    const mobile = document.getElementById('adminMobile').value;
    const gender = document.getElementById('adminGender').value;
    const amount = document.getElementById('adminAmount').value;

    if (!id || !name) {
        alert("দয়া করে অন্তত 'সদস্য নং' এবং 'দাতার নাম' লিখুন!");
        return;
    }

    const existingIndex = donors.findIndex(d => d.id === id);
    if (existingIndex !== -1) {
        donors[existingIndex] = { id, name, father, address, mobile, gender, amount };
        alert("দাতার তথ্য সফলভাবে আপডেট করা হয়েছে!");
    } else {
        donors.push({ id, name, father, address, mobile, gender, amount });
        alert("নতুন দাতা সফলভাবে যুক্ত করা হয়েছে!");
    }

    populateFilterOptions();
    applyFilters();
    
    document.getElementById('selectDonorToEdit').value = '';
    loadDonorForEdit('');
}

