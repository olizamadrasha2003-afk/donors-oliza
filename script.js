function populateFilterOptions() {
    const filters = {
        idFilter: 'id',
        nameFilter: 'name',
        fatherFilter: 'father',
        addressFilter: 'address',
        mobileFilter: 'mobile',
        genderFilter: 'gender',
        amountFilter: 'amount'
    };

    for (const [filterId, key] of Object.entries(filters)) {
        const select = document.getElementById(filterId);
        if (!select) continue;
        const firstOptionText = select.options[0].text;
        select.innerHTML = `<option value="">${firstOptionText}</option>`;
        
        const uniqueValues = [...new Set(donors.map(d => d[key]).filter(val => val !== "" && val !== undefined))];
        uniqueValues.sort().forEach(val => {
            const opt = document.createElement('option');
            opt.value = val;
            opt.innerText = val;
            select.appendChild(opt);
        });
    }

    const editSelect = document.getElementById('selectDonorToEdit');
    if (editSelect) {
        editSelect.innerHTML = `<option value="">-- নতুন দাতা যুক্ত করতে খালি রাখুন --</option>`;
        donors.forEach(d => {
            const opt = document.createElement('option');
            opt.value = d.id;
            opt.innerText = `আইডি: ${d.id} - ${d.name}`;
            editSelect.appendChild(opt);
        });
    }
}

// কার্ড প্রদর্শন করা (অ্যাভতার হ্যান্ডেলিং সহ)
function displayDonors(data) {
    const grid = document.getElementById('donorGrid');
    const counter = document.getElementById('counterDisplay');
    if (counter) counter.innerText = `মোট দাতা: ${data.length} জন`;

    if (data.length === 0) {
        grid.innerHTML = '<p style="grid-column: 1/-1; text-align:center;">কোনো দাতার তথ্য পাওয়া যায়নি!</p>';
        return;
    }

    grid.innerHTML = data.map(d => {
        // জেন্ডার অনুযায়ী ডিফল্ট অবতার: পুরুষ হলে '0.jpg', মহিলা হলে '00.jpg'
        const defaultAvatar = (d.gender === 'মহিলা') ? 'photos/00.jpg' : 'photos/0.jpg';
        const realImg = `photos/${d.id}.jpg`;

        return `
            <div class="card">
                <div>
                    <div class="img-box" onclick="openZoom('${realImg}', '${d.name}')">
                        <img src="${realImg}" loading="lazy" onerror="this.src='${defaultAvatar}'">
                    </div>
                    <div class="info">
                        <h4 title="${d.name}">${d.name}</h4>
                        <p><strong>আইডি:</strong> ${d.id}</p>
                        <p><strong>পিতা:</strong> ${d.father || 'প্রযোজ্য নয়'}</p>
                        <p class="address-line"><strong>ঠিকানা:</strong> ${d.address || 'তথ্য নেই'}</p>
                        <p><strong>মোবাইল:</strong> ${d.mobile || 'নেই'}</p>
                        <p><strong>লিঙ্গ:</strong> ${d.gender || 'পুরুষ'}</p>
                        <p><strong>দান:</strong> ${d.amount ? d.amount + ' টাকা' : 'নেই'}</p>
                    </div>
                </div>
                <button class="fullscreen-btn" onclick="openZoom('${realImg}', '${d.name}')">🔍 ফুল স্ক্রিন</button>
            </div>
        `;
    }).join('');
}

// ফিল্টারিং লজিক
function applyFilters() {
    const search = document.getElementById('searchBox').value.toLowerCase();
    const idVal = document.getElementById('idFilter').value;
    const nameVal = document.getElementById('nameFilter').value;
    const fatherVal = document.getElementById('fatherFilter').value;
    const addressVal = document.getElementById('addressFilter').value;
    const mobileVal = document.getElementById('mobileFilter').value;
    const genderVal = document.getElementById('genderFilter').value;
    const amountVal = document.getElementById('amountFilter').value;

    const filtered = donors.filter(d => {
        const matchSearch = (d.name && d.name.toLowerCase().includes(search)) ||
                            (d.id && d.id.toString().includes(search)) ||
                            (d.mobile && d.mobile.includes(search));

        const matchId = !idVal || d.id.toString() === idVal;
        const matchName = !nameVal || d.name === nameVal;
        const matchFather = !fatherVal || d.father === fatherVal;
        const matchAddress = !addressVal || d.address === addressVal;
        const matchMobile = !mobileVal || d.mobile === mobileVal;
        const matchGender = !genderVal || d.gender === genderVal;
        const matchAmount = !amountVal || d.amount === amountVal;

        return matchSearch && matchId && matchName && matchFather && matchAddress && matchMobile && matchGender && matchAmount;
    });

    displayDonors(filtered);
}

